"""Generate docs/examples sample reports from unit-test-shaped fixtures (offline).

Run from repo root: python scripts/gen_docs_examples.py
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from deadstick.evaluate.runner import evaluate_rule
from deadstick.metadata import load_metadata
from deadstick.param_file import load_param_file
from deadstick.provenance import build_provenance
from deadstick.report.json_report import write_result_json
from deadstick.report.md_report import write_report_md
from deadstick.rules.loader import load_rule
from deadstick.timeline.jsonl import load_jsonl

HDR = (
    "<!-- Example output from test fixtures, not a live flight. -->\n"
    "<!-- Generated by scripts/gen_docs_examples.py -->\n\n"
)


def main() -> None:
    repo = Path(__file__).resolve().parents[1]
    rule_path = repo / "rules" / "copter" / "r01_rc_loss_disarmed_blocks_arming.yaml"
    param_path = repo / "tests" / "fixtures" / "params" / "default.param"
    meta_path = repo / "metadata" / "Copter-4.7.2.json"
    out_dir = repo / "docs" / "examples"
    out_dir.mkdir(parents=True, exist_ok=True)
    tl_path = out_dir / "r01_unit_fixture.jsonl"

    lines = [
        '{"t_boot_ms": 800.0, "type": "fault_injected", "payload": {"kind": "rc_loss_while_disarmed"}}',
        '{"t_boot_ms": 810, "type": "statustext", "payload": {"text": "PreArm: Radio failsafe on"}}',
        '{"t_boot_ms": 920, "type": "statustext", "payload": {"text": "PreArm: Radio failsafe on"}}',
    ]
    tl_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    rule = load_rule(rule_path)
    params = load_param_file(param_path)
    meta = load_metadata(meta_path)
    timeline = load_jsonl(tl_path)
    prov = build_provenance(
        param_path=param_path,
        rule_path=rule_path,
        extra={"example": "unit-fixture"},
        relative_to=repo,
    )
    rows = evaluate_rule(rule=rule, params=params, metadata=meta, timeline=timeline)
    rows = [replace(r, provenance={**r.provenance, **prov}) for r in rows]

    pjson = out_dir / "r01_unit_fixture_result.json"
    pmd = out_dir / "r01_unit_fixture_report.md"
    write_result_json(pjson, rule_id=rule.id, results=rows, provenance=prov, timeline_path=tl_path)
    write_report_md(
        pmd,
        rule_id=rule.id,
        rule_say=rule.say,
        results=rows,
        provenance={k: v for k, v in prov.items()},
    )
    for path in (pjson, pmd):
        body = path.read_text(encoding="utf-8")
        if not body.startswith("<!-- Example"):
            path.write_text(HDR + body, encoding="utf-8")
    print("Wrote", tl_path, pjson, pmd)


if __name__ == "__main__":
    main()
